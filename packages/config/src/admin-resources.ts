import type { AdminDomain } from "./admin";

export type AdminFieldType =
  | "text"
  | "textarea"
  | "localized"
  | "number"
  | "money"
  | "boolean"
  | "select"
  | "date"
  | "reference"
  | "references"
  | "urls"
  | "lines"
  | "hours"
  | "breaks"
  | "dates"
  | "blocks"
  | "json";
export interface AdminField {
  key: string;
  type: AdminFieldType;
  required?: boolean;
  options?: string[];
  resource?: string;
  min?: number;
  max?: number;
  immutable?: boolean;
}
export interface AdminResource {
  key: string;
  domain: AdminDomain;
  collection: string;
  title: string;
  group: string;
  columns: string[];
  search: string[];
  fields: AdminField[];
  create?: boolean;
  readonly?: boolean;
  filter?: Record<string, unknown>;
}
const f = (
  key: string,
  type: AdminFieldType = "text",
  required = false,
  extra: Partial<AdminField> = {},
): AdminField => ({ key, type, required, ...extra });
const select = (key: string, options: string[], required = false) =>
  f(key, "select", required, { options });
const ref = (key: string, resource: string, required = false) =>
  f(key, "reference", required, { resource });
const refs = (key: string, resource: string) => f(key, "references", false, { resource });
const localized = (key: string, required = false) => f(key, "localized", required);
const contentFields = [
  f("slug", "text", true),
  select(
    "kind",
    ["page", "homepage", "journal", "magazine", "faq", "navigation", "footer"],
    true,
  ),
  localized("title", true),
  localized("summary"),
  f("coverImage", "text"),
  localized("category"),
  f("categorySlug", "text"),
  f("author", "text"),
  f("datePublished", "date"),
  f("readingTimeMinutes", "number"),
  f("sourceUrl", "text"),
  f("blocks", "blocks"),
  localized("seoTitle"),
  localized("seoDescription"),
  select("status", ["draft", "published", "archived"], true),
];

